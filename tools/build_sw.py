"""build_sw.py — regenerate sw.js with the list of files to cache offline.

Run after changing any file:  python tools/build_sw.py
The cache version is a hash of every cached file, so a deploy with changes
makes browsers fetch the new lessons and shows the "New lessons are ready" prompt.
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKIP_DIRS = {"tools", ".git", ".github", "node_modules"}
SKIP_FILES = {"sw.js", "README.md", ".nojekyll", "CNAME"}
EXTS = {".html", ".css", ".js", ".json", ".webmanifest", ".svg", ".png", ".woff2"}


def cached_files(root: Path) -> list[str]:
    """List site files to precache.

    Args:
        root: Project root folder.

    Returns:
        Sorted list of paths relative to root, using forward slashes.
    """
    out = []
    for p in root.rglob("*"):
        if not p.is_file() or p.suffix not in EXTS or p.name in SKIP_FILES:
            continue
        rel = p.relative_to(root)
        if rel.parts[0] in SKIP_DIRS:
            continue
        out.append(rel.as_posix())
    return sorted(out)


def version_hash(root: Path, files: list[str]) -> str:
    """Hash file contents into a short version string.

    Args:
        root: Project root folder.
        files: Relative file paths.

    Returns:
        12-character hex digest.
    """
    h = hashlib.sha256()
    for f in files:
        h.update(f.encode())
        h.update((root / f).read_bytes())
    return h.hexdigest()[:12]


TEMPLATE = """/* sw.js — generated by tools/build_sw.py. Do not edit by hand. */
const VERSION = '__VERSION__';
const CACHE = 'sparklab-' + VERSION;
const FILES = __FILES__;

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(['./', ...FILES])));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('sparklab-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('message', (e) => { if (e.data === 'skip-waiting') self.skipWaiting(); });

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
      return res;
    }).catch(() => caches.match('./index.html'))),
  );
});
"""


def main() -> None:
    """Write sw.js next to index.html.

    Returns:
        None.
    """
    files = cached_files(ROOT)
    ver = version_hash(ROOT, files)
    text = TEMPLATE.replace("__VERSION__", ver).replace("__FILES__", json.dumps(files, indent=1))
    (ROOT / "sw.js").write_text(text, encoding="utf-8")
    print(f"sw.js written: {len(files)} files, version {ver}")


if __name__ == "__main__":
    main()
